-- git_allowed_destinations 是允许出站到达的**私有**网段，CIDR，一行一条。
--
-- 空表示只放行公网——也就是引入这一列之前的行为。**没有"默认放行内网"
-- 这一档**：一次升级不该悄悄改变任何现有部署的出站面
-- （design doc 2026-09-01 §3.3），因此默认值是空串而不是任何网段。
--
-- 它只影响私有地址那一档。回环、链路本地与云元数据网段在这份清单**之上**，
-- 改不了：前者一旦可放行，平台就成了本机服务的探测器；后者一旦可放行，
-- 平台就成了一把偷取实例凭据的钥匙（§3.1）。
ALTER TABLE platform_setting
  ADD COLUMN git_allowed_destinations TEXT NOT NULL;
