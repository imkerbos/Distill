-- 回滚流量事实层。
--
-- 顺序与 up 相反：先删引用方 observed_connection，再删被引用的
-- flow_ingest_run，否则外键会挡住后者。
--
-- 丢掉的是**观测到的事实，不是可以重新推导出来的产物** —— 与 000012 的区间表
-- 正好相反。那张表回滚之后可以照着 observed_pod 重推，这两张不行：流量只在
-- 摄入的那一刻存在，relay 不保留历史。回滚等于永久丢掉那几段窗口的观测，
-- 而丢掉之后那些窗口读起来会变成"没有任何摄入记录"—— 那正是本轮反复要求
-- 与"这段时间没有流量"区分开的那一档。这是本次回滚的已知代价，不是遗漏。
DROP TABLE observed_connection;

DROP TABLE flow_ingest_run;
